"""Known-open campground searches with independent campsite expectations."""

from dataclasses import dataclass
from datetime import date

from camply.db.data.providers import RecreationDotGov
from camply.providers.dto import CampsiteType


@dataclass(frozen=True)
class AvailabilityCase:
    """Stable identity and inputs for replaying a recorded search."""

    key: str
    provider_id: int
    campground_id: str
    campground_name: str
    booking_url: str
    arrival: date
    checkout: date
    campsite_id: str
    campsite_name: str
    nights: tuple[date, ...]
    campsite_type: CampsiteType | None = None
    min_rv_length: int | None = None
    excluded_site_ids: tuple[str, ...] = ()


def validate_availability_cases(cases: tuple[AvailabilityCase, ...]) -> None:
    """Validate the complete set of scenarios before pytest selects cases."""
    seen: set[str] = set()
    for case in cases:
        if case.key in seen:
            raise ValueError(f"{case.key}: duplicate cassette key")
        seen.add(case.key)

        if case.checkout <= case.arrival:
            raise ValueError(f"{case.key}: checkout must follow arrival")
        if not case.campsite_id.strip():
            raise ValueError(f"{case.key}: expected campsite ID is required")
        if not case.nights:
            raise ValueError(f"{case.key}: expected nights are required")
        if any(not case.arrival <= night < case.checkout for night in case.nights):
            raise ValueError(f"{case.key}: expected nights outside the stay")


